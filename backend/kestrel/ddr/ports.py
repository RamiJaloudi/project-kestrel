"""Server-owned adapters must enforce current ABAC, processing, attempts and budgets.

execute_once must serialize claims across workers, retain ambiguous paid attempts,
and never automatically rerun a producer after unknown provider completion.
Approval lookup must recheck independent current source clearance and exact hashes.
No port grants permissions, approves a report, or releases anything externally.
"""
from typing import Callable, Protocol
from .schemas import ApprovalReceipt, Artifact, ArtifactRef, EvidenceBundle, RunSpec, Usage


class GraphPorts(Protocol):
    def authorize(self, spec: RunSpec, stage: str) -> None: ...
    def evidence(self, spec: RunSpec) -> EvidenceBundle: ...
    def execute_once(self, spec: RunSpec, step: str, input_hash: str, producer: Callable[[], Artifact]) -> ArtifactRef: ...
    def artifact(self, spec: RunSpec, reference: ArtifactRef) -> Artifact: ...
    def reserve(self, spec: RunSpec, step: str, estimated_input_tokens: int, max_output_tokens: int, live: bool) -> str: ...
    def settle(self, spec: RunSpec, reservation: str, usage: Usage | None, uncertain: bool) -> None: ...
    def review_task(self, spec: RunSpec, draft: ArtifactRef, validation: ArtifactRef, key: str) -> str: ...
    def approval(self, spec: RunSpec, draft: ArtifactRef, validation: ArtifactRef) -> ApprovalReceipt | None: ...
